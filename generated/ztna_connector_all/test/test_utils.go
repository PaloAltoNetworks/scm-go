// SetupZtnaConnectorAllTestClient creates an authenticated API client for ztna_connector_all.
func SetupZtnaConnectorAllTestClient(t *testing.T) *ztna_connector_all.APIClient {
	t.Helper()
	configPath := common.GetConfigPath()
	setupClient := &setup.Client{
		AuthFile:         configPath,
		CheckEnvironment: false,
	}
	fmt.Printf("Using config file: %s\n", setupClient.AuthFile)

	err := setupClient.Setup()
	require.NoError(t, err, "Failed to setup client")

	// Prevent JWTRefreshTransport from trying to refresh a static JWT without expiry.
	if setupClient.Jwt != "" && setupClient.JwtExpiresAt.IsZero() {
		setupClient.JwtExpiresAt = time.Now().Add(1 * time.Hour)
	}

	ctx := context.Background()
	if setupClient.Jwt == "" {
		fmt.Printf("\n****************\nGetting tokens\n***********************\n")
		err = setupClient.RefreshJwt(ctx)
		if err != nil {
			fmt.Printf("=== JWT REFRESH ERROR ===\nError: %v\n=========================\n", err)
		}
		require.NoError(t, err, "Failed to refresh JWT")
	}

	cfg := ztna_connector_all.NewConfiguration()
	cfg.Servers[0].URL = fmt.Sprintf("https://%s/sse/connector/v2.0/api", setupClient.GetZtnaHost())
	if region := setupClient.GetXPanwRegion(); region != "" {
		cfg.AddDefaultHeader("x-panw-region", region)
	}

	jwtTransport := &setup.JWTRefreshTransport{
		Wrapped:     setupClient.HttpClient.Transport,
		SetupClient: setupClient,
	}
	cfg.HTTPClient = &http.Client{
		Transport: &common.LoggingRoundTripper{Wrapped: jwtTransport},
		Timeout:   setupClient.HttpClient.Timeout,
	}

	return ztna_connector_all.NewAPIClient(cfg)
}

// setupTestClient is the unexported alias used by lifecycle tests generated by the test generator.
func setupTestClient(t *testing.T) *ztna_connector_all.APIClient {
	return SetupZtnaConnectorAllTestClient(t)
}

func printAPIError(err *ztna_connector_all.GenericOpenAPIError) {
	if err == nil {
		return
	}
	fmt.Printf("=== API ERROR RESPONSE ===\nError: %v\n", err)
	bodyBytes := err.Body()
	if len(bodyBytes) == 0 {
		fmt.Printf("No body found in error object\n===========================\n\n")
		return
	}
	fmt.Printf("Raw Error Body:\n%s\n===========================\n\n", string(bodyBytes))
}

func handleAPIError(err error) {
	if err == nil {
		return
	}
	var apiErr *ztna_connector_all.GenericOpenAPIError
	if errors.As(err, &apiErr) {
		printAPIError(apiErr)
	} else {
		fmt.Printf("Non-API Error: %v\n", err)
	}
}

// ── Self-provisioning helpers ─────────────────────────────────────────────────

// provisionGroupID creates a temporary connector group for the duration of the test,
// registers t.Cleanup to delete it, and returns the group OID. This makes lifecycle
// tests fully self-contained with no environment variable dependencies.
func provisionGroupID(t *testing.T, client *ztna_connector_all.APIClient) string {
	t.Helper()
	name := "test-group-" + common.GenerateRandomString(8)
	createTestConnectorGroup(t, client, name)
	oid := fetchTestConnectorGroupOID(t, client, name)
	t.Cleanup(func() {
		deleteTestConnectorGroup(t, client, oid, name)
	})
	return oid
}

// ── Connector-Group helpers ───────────────────────────────────────────────────

// createTestConnectorGroup creates a connector group and asserts 201.
func createTestConnectorGroup(t *testing.T, client *ztna_connector_all.APIClient, name string) {
	t.Helper()
	group := ztna_connector_all.ConnectorGroups{Name: name}
	httpRes, err := client.ConnectorGroupAPI.CreateConnectorGroup(context.Background()).
		ConnectorGroups(group).Execute()
	if err != nil {
		handleAPIError(err)
	}
	require.NoError(t, err, "Failed to create test connector group")
	require.NotNil(t, httpRes)
	require.Equal(t, 201, httpRes.StatusCode, "Expected 201 Created")
	t.Logf("Created test connector group: %s", name)
}

// fetchTestConnectorGroupOID finds a connector group by name via list and returns its OID.
func fetchTestConnectorGroupOID(t *testing.T, client *ztna_connector_all.APIClient, name string) string {
	t.Helper()
	listRes, httpRes, err := client.ConnectorGroupAPI.ListConnectorGroups(context.Background()).Execute()
	if err != nil {
		handleAPIError(err)
	}
	require.NoError(t, err, "Failed to list connector groups")
	require.Equal(t, 200, httpRes.StatusCode)
	require.NotNil(t, listRes)

	for _, g := range listRes.GetData() {
		if g.Name == name {
			oid := g.GetOid()
			require.NotEmpty(t, oid, "Connector group %s should have an OID", name)
			t.Logf("Found connector group %s with OID: %s", name, oid)
			return oid
		}
	}
	t.Fatalf("Connector group %q not found in list", name)
	return ""
}

// deleteTestConnectorGroup deletes a connector group by OID. Treats 404 as already deleted.
func deleteTestConnectorGroup(t *testing.T, client *ztna_connector_all.APIClient, oid, name string) {
	t.Helper()
	httpRes, err := client.ConnectorGroupAPI.DeleteConnectorGroupByID(context.Background(), oid).Execute()
	if err != nil {
		if httpRes != nil && httpRes.StatusCode == 404 {
			t.Logf("Connector group already deleted (OID: %s)", oid)
			return
		}
		handleAPIError(err)
		require.Fail(t, "Failed to delete test connector group", "OID: %s", oid)
	}
	t.Logf("Deleted test connector group: %s (OID: %s)", name, oid)
}

